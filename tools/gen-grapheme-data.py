"""Emit `CTGraphemeData.c`: the Grapheme_Cluster_Break classes and the Extended_Pictographic ranges.

Two UCD files are read, both Unicode 15.1.0, neither committed (the same standing every other UCD file has):

    auxiliary/GraphemeBreakProperty.txt — the GCB value of every code point that has one
    emoji/emoji-data.txt                — Extended_Pictographic, which GB11 needs and which is NOT a GCB value

    curl -o /tmp/GraphemeBreakProperty.txt \\
        https://www.unicode.org/Public/15.1.0/ucd/auxiliary/GraphemeBreakProperty.txt
    curl -o /tmp/emoji-data.txt https://www.unicode.org/Public/15.1.0/ucd/emoji/emoji-data.txt

    python3 tools/gen-grapheme-data.py > CTGraphemeData.c

THE TWO TABLES ARE SEPARATE BECAUSE THE PROPERTIES ARE: a character has a GCB value AND may be
Extended_Pictographic — © is `Other` and a pictograph — so folding the second into the first would lose cases.
Both are RANGES and both are searched by binary search; unlisted code points are `Other`, which is the default.

THE CLASS ORDER HERE IS THE ENUM'S ORDER IN `CTGrapheme_internal.h`, and the two must not drift: the table stores
the enum value, so a reordering of one without the other is a silent misreading.
"""
import re
import sys

GCB_PATH = "/tmp/GraphemeBreakProperty.txt"
EMOJI_PATH = "/tmp/emoji-data.txt"
INCB_PATH = "/tmp/DerivedCoreProperties.txt"

# The property value's name → the enum's name, in the enum's order.
CLASSES = [
    ("CR", "kCTGcbCR"),
    ("LF", "kCTGcbLF"),
    ("Control", "kCTGcbControl"),
    ("Extend", "kCTGcbExtend"),
    ("ZWJ", "kCTGcbZWJ"),
    ("Regional_Indicator", "kCTGcbRegionalIndicator"),
    ("Prepend", "kCTGcbPrepend"),
    ("SpacingMark", "kCTGcbSpacingMark"),
    ("L", "kCTGcbL"),
    ("V", "kCTGcbV"),
    ("T", "kCTGcbT"),
    ("LV", "kCTGcbLV"),
    ("LVT", "kCTGcbLVT"),
]
# **AND `Indic_Conjunct_Break`, WHICH IS NOT A GCB VALUE EITHER.** GB9c is Unicode 15.1's new rule: a consonant, then
# extenders and at least one LINKER, then a consonant, is ONE cluster — a Devanagari aksara. The property lives in
# `DerivedCoreProperties.txt`, next to `Indic_Conjunct_Break`, and without it seven of the data's 1,187 strings fail.
INCB_NAMES = dict([("Consonant", "kCTIncbConsonant"), ("Linker", "kCTIncbLinker"), ("Extend", "kCTIncbExtend")])
BY_NAME = dict(CLASSES)


def ranges(path, wanted):
    """Every (first, last, value) whose property value is in `wanted`, from a `UCD` property file."""
    out = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            body = line.split("#")[0].strip()
            if not body:
                continue
            fields = [f.strip() for f in body.split(";")]
            if len(fields) < 2:
                continue
            value = fields[1].split()[0]
            if len(fields) > 2 and value == "InCB":
                # DerivedCoreProperties states "code ; InCB ; Linker" — the value is the THIRD field.
                value = fields[2].split()[0]
            if value not in wanted:
                continue
            span = fields[0]
            if ".." in span:
                first, last = span.split("..")
            else:
                first = last = span
            out.append((int(first, 16), int(last, 16), value))
    out.sort()
    return out


def merge(rows):
    """Adjacent or overlapping ranges of the SAME value, so the table is the smallest that answers the same."""
    merged = []
    for first, last, value in rows:
        if merged and merged[-1][2] == value and first <= merged[-1][1] + 1:
            merged[-1] = (merged[-1][0], max(merged[-1][1], last), value)
        else:
            merged.append((first, last, value))
    return merged


def main():
    write = sys.stdout.write
    gcb = merge(ranges(GCB_PATH, set(BY_NAME)))
    incb = merge(ranges(INCB_PATH, set(INCB_NAMES)))
    pict = merge(ranges(EMOJI_PATH, {"Extended_Pictographic"}))
    write("""/*
 * CTGraphemeData.c — the Grapheme_Cluster_Break classes and the Extended_Pictographic ranges.
 *
 * Copyright © 2026 Kyle J. Cardoza.
 * SPDX-FileCopyrightText: 2026 Kyle J. Cardoza
 * SPDX-License-Identifier: LGPL-3.0-or-later
 * Portions of this file may derive from GNUstep; see THIRD-PARTY.md.
 *
 * GENERATED BY `tools/gen-grapheme-data.py` FROM Unicode 15.1.0's `auxiliary/GraphemeBreakProperty.txt` and
 * `emoji/emoji-data.txt`. Do not edit; regenerate. Both files are absent from this repository by the standing rule
 * for UCD data: the recipe is kept, the data is not.
 */
#include <CoreText/CTGrapheme_internal.h>

/* ONE ROW PER RANGE, in code point order. Unlisted code points are `kCTGcbOther`, which is the UCD's default and so
 * is not stored: a table cannot know whether a code point was LISTED. */
const struct ct_gcb_range ct_gcb_ranges[] = {
""")
    for first, last, value in gcb:
        write("\t{ 0x%04X, 0x%04X, %s },\n" % (first, last, BY_NAME[value]))
    write("""};

const size_t ct_gcb_range_count = sizeof ct_gcb_ranges / sizeof ct_gcb_ranges[0];

/* AND THE PICTOGRAPHS SEPARATELY, because `Extended_Pictographic` is not a `Grapheme_Cluster_Break` value: it is a
 * SECOND property of the same character, and GB11 needs both. */
const struct ct_extpict_range ct_extpict_ranges[] = {
""")
    for first, last, _ in pict:
        write("\t{ 0x%04X, 0x%04X },\n" % (first, last))
    write("""};

const size_t ct_extpict_range_count = sizeof ct_extpict_ranges / sizeof ct_extpict_ranges[0];

/* AND THE `Indic_Conjunct_Break` SET, which GB9c reads: a THIRD property, from `DerivedCoreProperties.txt`. */
const struct ct_incb_range ct_incb_ranges[] = {
""")
    for first, last, value in incb:
        write("\t{ 0x%04X, 0x%04X, %s },\n" % (first, last, INCB_NAMES[value]))
    write("""};

const size_t ct_incb_range_count = sizeof ct_incb_ranges / sizeof ct_incb_ranges[0];
""")


if __name__ == "__main__":
    main()
